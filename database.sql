CREATE DATABASE IF NOT EXISTS us_stock_portfolio
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE us_stock_portfolio;

CREATE TABLE IF NOT EXISTS holdings (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ticker VARCHAR(15) NOT NULL UNIQUE,
  company_name VARCHAR(120) DEFAULT NULL,
  strategy ENUM('short','long') NOT NULL DEFAULT 'long',
  quantity DECIMAL(18,6) NOT NULL DEFAULT 0,
  avg_cost DECIMAL(18,6) NOT NULL DEFAULT 0,
  current_price DECIMAL(18,6) NOT NULL DEFAULT 0,
  ema20 DECIMAL(18,6) DEFAULT NULL,
  ema50 DECIMAL(18,6) DEFAULT NULL,
  rsi14 DECIMAL(8,3) DEFAULT NULL,
  support_price DECIMAL(18,6) DEFAULT NULL,
  resistance_price DECIMAL(18,6) DEFAULT NULL,
  notes TEXT DEFAULT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  holding_id INT UNSIGNED NOT NULL,
  trade_date DATE NOT NULL,
  side ENUM('BUY','SELL','DIVIDEND') NOT NULL,
  quantity DECIMAL(18,6) NOT NULL DEFAULT 0,
  price DECIMAL(18,6) NOT NULL DEFAULT 0,
  fees DECIMAL(18,6) NOT NULL DEFAULT 0,
  notes VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_transactions_holding FOREIGN KEY (holding_id)
    REFERENCES holdings(id) ON DELETE CASCADE
);
